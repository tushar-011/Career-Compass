// ================= SIDEBAR =================
function toggleSidebar() {
    const sidebar = document.getElementById("sidebar");
    const overlay = document.getElementById("overlay");
    const hamburger = document.querySelector(".hamburger");
    
    if (sidebar && overlay) {
        sidebar.classList.toggle("active");
        overlay.classList.toggle("active");
        if (hamburger) hamburger.classList.toggle("active");
    }
}

// ================= THEME TOGGLE =================
function toggleTheme() {
    const body = document.body;
    const btn = document.querySelector(".theme-toggle");
    body.classList.toggle("light-mode");
    
    const isLight = body.classList.contains("light-mode");
    btn.textContent = isLight ? "☀️" : "🌙";
    localStorage.setItem("theme", isLight ? "light" : "dark");
}

// ================= NAVIGATION LOGIC =================
function showSection(sectionId) {
    const sections = {
        dashboard: document.getElementById('default-dashboard'),
        roadmap: document.getElementById('roadmap-section'),
        construction: document.getElementById('construction-section')
    };

    // Hide all sections
    Object.values(sections).forEach(s => { if(s) s.style.display = 'none'; });

    if (sectionId === 'dashboard') {
        sections.dashboard.style.display = 'block';
    } 
    else if (sectionId === 'roadmap') {
        sections.roadmap.style.display = 'block';
        
        const aiContent = localStorage.getItem("aiRoadmap");
        const roadmapTextElement = sections.roadmap.querySelector('.timeline-content p');
        const roadmapTitle = sections.roadmap.querySelector('.welcome h1');
        const roadmapDesc = sections.roadmap.querySelector('.section-desc');

        if (aiContent && roadmapTextElement) {
            roadmapTitle.innerText = "Your AI Strategic Roadmap";
            roadmapDesc.innerText = "Generated by Gemini based on your latest assessment.";
            roadmapTextElement.innerHTML = aiContent.replace(/\n/g, "<br><br>");
        }
    }
    else {
        sections.construction.style.display = 'block';
    }

    if (window.innerWidth < 1024) toggleSidebar();
}

// ================= MODAL LOGIC =================
function openProfileModal() {
    const modal = document.getElementById("profileModal");
    if (modal) {
        modal.style.display = "flex";
        document.body.style.overflow = "hidden";
    }
}

function closeProfileModal() {
    const modal = document.getElementById("profileModal");
    if (modal) {
        modal.style.display = "none";
        document.body.style.overflow = "auto";
    }
}

// ================= INITIALIZATION (Combined window.onload) =================
window.onload = function() {
    // 1. Theme Initialization
    const savedTheme = localStorage.getItem("theme");
    const themeBtn = document.querySelector(".theme-toggle");
    if (savedTheme === "light") {
        document.body.classList.add("light-mode");
        if (themeBtn) themeBtn.textContent = "☀️";
    }

    // 2. User Data Population
    const userName = localStorage.getItem("userName") || "Strategic User";
    const userEmail = localStorage.getItem("userEmail") || "verified.student@university.edu";

    const welcome = document.getElementById("welcomeText");
    if (welcome) welcome.innerHTML = `Welcome Back, ${userName} 👋`;

        // 3. Dashboard Goal Card from AI Roadmap
    const aiRoadmap = localStorage.getItem("aiRoadmap");
    const goalCardTitle = document.getElementById("goalCardTitle");
    const goalCardText = document.getElementById("goalCardText");

    if (aiRoadmap && goalCardText) {
        const cleaned = aiRoadmap.replace(/[#*]/g, "").trim();

        let summary = cleaned.split("\n").find(line => 
            line.trim() && 
            !line.toLowerCase().includes("welcome to career compass") &&
            !line.toLowerCase().includes("hello ")
        );

        if (!summary) {
            summary = "Your personalized roadmap is now active. Open Career Roadmap to view your AI-generated plan.";
        }

        if (goalCardTitle) goalCardTitle.innerText = "AI Career Direction";
        goalCardText.innerText = summary;
    }

    // 3. Cursor Glow Effect
    const glow = document.querySelector(".cursor-glow");
    if (glow) {
        document.addEventListener("mousemove", (e) => {
            glow.style.left = e.clientX + "px";
            glow.style.top = e.clientY + "px";
        });
    }
};

// ================= LOGOUT =================
function logout() {
    localStorage.clear();
    alert("Career Compass Session Terminated Successfully.");
    window.location.href = "MainWeb.html";
}